/**
 * Pure logic of «Қазақстан саяхаты» (phase 2 «Мектеп», geography 3–4 — a 3D map of Kazakhstan with a toy plane).
 *  - tour: the architect wants to see a landmark — «Мен Бәйтеректі көргім келеді. Қай қалаға барамыз?»; three cities
 *          are lit on the map, the child picks one, the plane flies there and the narrator says «Бәйтерек — Астанада.»
 *  - map:  «Шымкент қай жерде?» — three unnamed pins on the map; tap the right one (names show after the answer).
 *  - compass: «Астанадан Шымкентке қай жаққа ұшамыз?» — the side of the world; legs chain (the plane flies on), only clear
 *            pairs (within 15° of a side); wrong options are the opposite side and a side at 90°.
 * Every fact and every sentence comes from the main game (data/travelData.ts, generated by tools/build-travel.js).
 * Candidate pins are ≥ MAP_GAP apart on the 600 × 340 map, so neighbouring cities never compete on a phone.
 */
import { CITIES, COMPASS_Q, LEGS, MAP_GAP, SIDES, TOUR, type TravelCity, type TravelLeg } from '../data/travelData';
import { shuffle, type Rng } from './totemLogic';

export type TravelMode = 'tour' | 'map' | 'compass';
export const V_TASKS = 8, V_LIVES = 3;
/** speak: the voiced line (compass: one short question); target: the city the plane flies to; start: where a leg begins. */
export interface VStage { landmark: string | null; prompt: string; speak: string; answer: string; options: string[]; say: string; target: string; start: string | null }
export interface VRound { mode: TravelMode; stages: VStage[] }
export const cityOf = (name: string): TravelCity => CITIES.find((c) => c.name === name)!;
const dist = (a: string, b: string) => { const A = cityOf(a), B = cityOf(b); return Math.hypot(A.x - B.x, A.y - B.y); };

/** The answer and two more cities, all ≥ MAP_GAP apart (and in random order). */
export function candidates(answer: string, rng: Rng): string[] {
  const pick = [answer];
  for (const c of shuffle(CITIES.map((x) => x.name), rng)) if (pick.length < 3 && !pick.includes(c) && pick.every((p) => dist(p, c) >= MAP_GAP)) pick.push(c);
  return shuffle(pick, rng);
}

const degOf = (dir: string) => SIDES.find((s) => s.dir === dir)!.deg;
const sideAt = (deg: number) => SIDES.find((s) => ((s.deg - deg + 720) % 360) === 0)!.dir;
/** The right side, its opposite and one of the two sides at 90° — never a neighbouring side, so no option is «almost right». */
export function sideOptions(dir: string, rng: Rng): string[] {
  const d = degOf(dir);
  return shuffle([dir, sideAt(d + 180), sideAt(d + (rng() < 0.5 ? 90 : -90))], rng);
}
/** Eight legs; each starts where the last one ended when it can (the plane flies on), different legs every time. */
export function legChain(rng: Rng): TravelLeg[] {
  const out: TravelLeg[] = [], used = new Set<string>();
  let cur = shuffle(LEGS.slice(), rng)[0].from;
  for (let g = 0; out.length < V_TASKS && g < 200; g++) {
    const next = shuffle(LEGS.filter((l) => l.from === cur && !used.has(l.from + '>' + l.to)), rng)[0] ?? shuffle(LEGS.filter((l) => !used.has(l.from + '>' + l.to)), rng)[0];
    used.add(next.from + '>' + next.to); out.push(next); cur = next.to;
  }
  return out;
}

export function buildTravelRound(mode: TravelMode, rng: Rng = Math.random): VRound {
  if (mode === 'tour') {
    const stops = shuffle(TOUR.slice(), rng).slice(0, V_TASKS);
    return { mode, stages: stops.map((s) => ({ landmark: s.landmark, prompt: s.line, speak: s.line, answer: s.city, options: candidates(s.city, rng), say: s.place, target: s.city, start: null })) };
  }
  if (mode === 'compass') return { mode, stages: legChain(rng).map((l) => ({ landmark: null, prompt: l.ask, speak: COMPASS_Q, answer: l.dir, options: sideOptions(l.dir, rng), say: l.say, target: l.to, start: l.from })) };
  const cs = shuffle(CITIES.slice(), rng).slice(0, V_TASKS);
  return { mode, stages: cs.map((c) => ({ landmark: null, prompt: c.ask, speak: c.ask, answer: c.name, options: candidates(c.name, rng), say: c.where, target: c.name, start: null })) };
}

export type VPhase = 'intro' | 'aim' | 'hit' | 'miss' | 'victory' | 'defeat';
export interface VState { round: VRound | null; phase: VPhase; i: number; lives: number; xp: number; combo: number; bestCombo: number; firstTry: number; tried: string[]; from: string; seq: number }
export type VAction = { type: 'start'; round: VRound } | { type: 'pick'; option: string } | { type: 'next' };
/** The plane starts in the capital and flies on from each right answer. */
export const initialTravel = (): VState => ({ round: null, phase: 'intro', i: 0, lives: V_LIVES, xp: 0, combo: 0, bestCombo: 0, firstTry: 0, tried: [], from: 'Астана', seq: 0 });
export function travelReducer(s: VState, a: VAction): VState {
  switch (a.type) {
    case 'start': return { ...initialTravel(), round: a.round, phase: 'aim', from: a.round.stages[0].start ?? 'Астана' };
    case 'pick': {
      if ((s.phase !== 'aim' && s.phase !== 'miss') || !s.round || s.tried.includes(a.option)) return s;
      const st = s.round.stages[s.i];
      if (!st.options.includes(a.option)) return s;
      if (a.option === st.answer) {
        const combo = s.combo + 1;
        return { ...s, phase: 'hit', combo, bestCombo: Math.max(s.bestCombo, combo), firstTry: s.firstTry + (s.tried.length ? 0 : 1), xp: s.xp + 50 + Math.min(combo - 1, 5) * 10, seq: s.seq + 1 };
      }
      const lives = s.lives - 1;
      return { ...s, phase: lives <= 0 ? 'defeat' : 'miss', lives, combo: 0, tried: [...s.tried, a.option], seq: s.seq + 1 };
    }
    case 'next': {
      if (s.phase !== 'hit' || !s.round) return s;
      const i = s.i + 1, from = s.round.stages[s.i].target, nx = s.round.stages[i];
      return i >= s.round.stages.length ? { ...s, phase: 'victory', from } : { ...s, phase: 'aim', i, tried: [], from: nx.start ?? from };
    }
  }
}
export const travelAccuracy = (s: VState) => ({ correct: s.firstTry, total: s.round ? s.round.stages.length : 0 });
