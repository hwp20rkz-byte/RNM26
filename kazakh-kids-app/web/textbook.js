  /* small Kazakh helpers used by the pair voice-overs */
  function cap(x) { return x.charAt(0).toUpperCase() + x.slice(1); }
  function lastVowel(x) { var m = x.match(/[аәеиоөұүыіуэюя](?=[^аәеиоөұүыіуэюя]*$)/); return m ? m[0] : 'а'; }
  // ілік септік: after a vowel -ның/-нің; after л м н ң ж з р й у -дың/-дің; after other consonants -тың/-тің
  function gen(x) {
    var back = /[аоұы]/.test(lastVowel(x)), c = x.slice(-1);
    return x + (/[аәеиоөұүыіэюя]/.test(c) ? (back ? 'ның' : 'нің') : /[лмнңжзрйу]/.test(c) ? (back ? 'дың' : 'дің') : (back ? 'тың' : 'тің'));
  }
  function poss(x) { return /[аәеоөұүыі]$/.test(x) ? x + (/[аоұы]/.test(lastVowel(x)) ? 'сы' : 'сі') : (x === 'лақ' ? 'лағы' : x + (/[аоұы]/.test(lastVowel(x)) ? 'ы' : 'і')); }

  /* Clock language for «Сағат шебері»: «Сағат жеті болды», «Оннан он минут кетті», «Екіге бес минут қалды». */
  var H = ['', 'бір', 'екі', 'үш', 'төрт', 'бес', 'алты', 'жеті', 'сегіз', 'тоғыз', 'он', 'он бір', 'он екі'];
  var ABL = ['', 'бірден', 'екіден', 'үштен', 'төрттен', 'бестен', 'алтыдан', 'жетіден', 'сегізден', 'тоғыздан', 'оннан', 'он бірден', 'он екіден'];
  var DAT = ['', 'бірге', 'екіге', 'үшке', 'төртке', 'беске', 'алтыға', 'жетіге', 'сегізге', 'тоғызға', 'онға', 'он бірге', 'он екіге'];
  var MIN = { 5: 'бес', 10: 'он', 15: 'он бес', 20: 'жиырма', 25: 'жиырма бес' };
  D.clockPhrase = function (h, m) {
    if (m === 0) return 'Сағат ' + H[h] + ' болды';
    if (m === 30) return 'Сағат ' + H[h] + ' жарым';
    if (m < 30) return cap(ABL[h]) + ' ' + MIN[m] + ' минут кетті';
    var nh = h % 12 + 1;
    return cap(DAT[nh]) + ' ' + MIN[60 - m] + ' минут қалды';
  };
