// Data for the 3D «Қазақстан саяхаты» → suite/src/data/travelData.ts. Everything comes from the main game, so the 3D hall
// never holds a fact of its own: the outline and the water (web/kz-map.js, Natural Earth), the cities and their places
// on the map (CITY_LL, cityWhere), the landmarks (TOUR, tourLine, travelPlace) and the gap between candidate pins.
//   node tools/build-travel.js            (suite/src/lib/travel.test.ts checks the file is up to date)
const fs = require('fs'), path = require('path');
global.window = global.window || global;
const M = require(path.join(__dirname, '../web/mektep-core.js')), K = require(path.join(__dirname, '../web/kz-map.js'));

/** «M1 2L3 4Z…» → [[[1,2],[3,4]], …] */
const rings = (d) => d.split('Z').filter((x) => x.trim()).map((r) => r.replace(/^M/, '').split('L').map((p) => p.trim().split(' ').map(Number)));

function build() {
  const r1 = (v) => Math.round(v * 10) / 10;
  return {
    W: K.W, H: K.H, gap: M.MAP_GAP,
    outline: rings(K.path),
    water: K.water.map((w) => ({ id: w.id, rings: rings(w.path), c: w.c })),
    cities: Object.keys(M.CITY_LL).map((c) => { const p = M.cityXY(c); return { name: c, x: r1(p[0]), y: r1(p[1]), ask: c + ' қай жерде?', where: M.cityWhere(c) }; }),
    tour: Object.keys(M.TOUR).map((n) => ({ landmark: n, city: M.TOUR[n], line: M.tourLine(n), to: M.guideForms(M.TOUR[n])[1], place: M.travelPlace(n) })),
    // compass (25.11): only clear pairs (within 15° of a side); the side words and their «…қа ұшамыз!» lines from the engine
    compassQ: M.COMPASS_Q,
    sides: M.COMPASS.map((c) => ({ dir: c[0], deg: c[1] })),
    compass: M.compassPairs().map((p) => ({ from: p.from, to: p.to, dir: p.dir, ask: p.ask, say: p.say }))
  };
}

function render(d) {
  return '/* Generated by tools/build-travel.js from web/kz-map.js and web/mektep-core.js — do not edit. */\n' +
    'export interface TravelCity { name: string; x: number; y: number; ask: string; where: string }\n' +
    'export interface TravelStop { landmark: string; city: string; line: string; to: string; place: string }\n' +
    'export interface TravelWater { id: string; rings: number[][][]; c: number[] }\n' +
    `export const MAP_W = ${d.W}, MAP_H = ${d.H}, MAP_GAP = ${d.gap};\n` +
    'export const OUTLINE: number[][][] = ' + JSON.stringify(d.outline) + ';\n' +
    'export const WATER: TravelWater[] = ' + JSON.stringify(d.water) + ';\n' +
    'export const CITIES: TravelCity[] = ' + JSON.stringify(d.cities) + ';\n' +
    'export const TOUR: TravelStop[] = ' + JSON.stringify(d.tour) + ';\n' +
    'export interface TravelLeg { from: string; to: string; dir: string; ask: string; say: string }\n' +
    'export const COMPASS_Q = ' + JSON.stringify(d.compassQ) + ';\n' +
    'export const SIDES: { dir: string; deg: number }[] = ' + JSON.stringify(d.sides) + ';\n' +
    'export const LEGS: TravelLeg[] = ' + JSON.stringify(d.compass) + ';\n';
}

module.exports = { build, render };
if (require.main === module) {
  const out = path.join(__dirname, '../suite/src/data/travelData.ts');
  fs.writeFileSync(out, render(build()));
  console.log(out, (fs.statSync(out).size / 1024).toFixed(1) + ' KB');
}
