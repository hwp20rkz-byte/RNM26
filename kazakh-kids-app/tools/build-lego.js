#!/usr/bin/env node
/* Generates suite/src/data/legoForms.ts for «Лего-Сөз» from web/grammar-core.js — the engine is the only source of
 * word forms (CLAUDE.md §2). Run after any engine change: node tools/build-lego.js  (suite/src/lib/lego.test.ts checks
 * that the file still matches the engine). */
const fs = require('fs'), path = require('path');
const G = require('../web/grammar-core.js');
// nouns of the engine + nouns that show the two sound changes: voicing (құлақ → құлағым) and a fleeting vowel (ауыз → аузым)
const EXTRA = [
  { kk: 'ауыз', ru: 'рот', en: 'mouth', e: '👄' }, { kk: 'мұрын', ru: 'нос', en: 'nose', e: '👃' },
  { kk: 'мойын', ru: 'шея', en: 'neck', e: '🦒' }, { kk: 'құлақ', ru: 'ухо', en: 'ear', e: '👂' },
  { kk: 'тарақ', ru: 'расчёска', en: 'comb', e: '🪮' }, { kk: 'етік', ru: 'сапог', en: 'boot', e: '👢' },
  { kk: 'жүрек', ru: 'сердце', en: 'heart', e: '❤️' }
];
const nouns = G.NOUNS.concat(EXTRA.filter((x) => !G.NOUNS.some((n) => n.kk === x.kk)));
const LEGO = nouns.map((n) => ({ kk: n.kk, ru: n.ru, en: n.en, e: n.e,
  forms: { men: G.possessive(n.kk, 'men'), sen: G.possessive(n.kk, 'sen'), ol: G.possessive(n.kk, 'ol'), biz: G.possessive(n.kk, 'biz'), pl: G.plural(n.kk) } }));
// «Аниматор»: a hero does something sitting / standing / lying, or has finished it (-ып тастады + a definite object)
const VERBS = [
  { stem: 'оқы', obj: 'кітап', e: '📖', ru: 'читать книгу', en: 'read a book' },
  { stem: 'жаз', obj: 'хат', e: '✉️', ru: 'писать письмо', en: 'write a letter' },
  { stem: 'же', obj: 'алма', e: '🍎', ru: 'есть яблоко', en: 'eat an apple' },
  { stem: 'іш', obj: 'шай', e: '🍵', ru: 'пить чай', en: 'drink tea' },
  { stem: 'тыңда', obj: 'ән', e: '🎧', ru: 'слушать песню', en: 'listen to a song' },
  { stem: 'сал', obj: 'сурет', e: '🎨', ru: 'рисовать картину', en: 'draw a picture' }
];
const POSE = VERBS.map((v) => ({ ...v, objAcc: G.caseForm(v.obj, 'tabys'),
  forms: { отыр: G.aux(v.stem, 'отыр', 'ol'), тұр: G.aux(v.stem, 'тұр', 'ol'), жатыр: G.aux(v.stem, 'жатыр', 'ol'), тастады: G.done(v.stem, 'ol') } }));
const out = '/* GENERATED by tools/build-lego.js from web/grammar-core.js — do not edit by hand. */\n' +
  'import type { LegoNoun, PoseVerb } from \'./legoTypes\';\n\n' +
  'export const LEGO_NOUNS: LegoNoun[] = ' + JSON.stringify(LEGO, null, 1) + ';\n\n' +
  'export const POSE_VERBS: PoseVerb[] = ' + JSON.stringify(POSE, null, 1) + ';\n';
fs.writeFileSync(path.join(__dirname, '../suite/src/data/legoForms.ts'), out);
console.log('legoForms.ts:', LEGO.length, 'nouns,', POSE.length, 'verbs');
