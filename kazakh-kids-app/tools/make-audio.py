#!/usr/bin/env python3
"""Synthesises every game phrase to web/audio/<key>.mp3 with the Piper Kazakh voice.

Voice: kk_KZ-issai-high (KazakhTTS by ISSAI, Nazarbayev University, CC BY 4.0).
  curl -L -O https://github.com/k2-fsa/sherpa-onnx/releases/download/tts-models/vits-piper-kk_KZ-issai-high.tar.bz2
  tar xjf vits-piper-kk_KZ-issai-high.tar.bz2
  pip install piper-tts      # plus ffmpeg on PATH
Usage:
  node tools/collect-phrases.js > /tmp/phrases.json
  python3 tools/make-audio.py /tmp/phrases.json path/to/kk_KZ-issai-high.onnx
Only missing files are generated; stale ones are removed; web/audio/index.js is rewritten.
"""
import json
import os
import subprocess
import sys
import tempfile
import wave

from piper import PiperVoice, SynthesisConfig

SPEAKER = 2          # a clear female voice of the six in the model
LENGTH_SCALE = 1.15  # a little slower than normal speech, for children

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_dir = os.path.join(root, 'web', 'audio')
os.makedirs(out_dir, exist_ok=True)

phrases = json.load(open(sys.argv[1], encoding='utf-8'))
model = sys.argv[2]
voice = PiperVoice.load(model, config_path=model + '.json')
cfg = SynthesisConfig(speaker_id=SPEAKER, length_scale=LENGTH_SCALE)

keys = set()
made = 0
for i, p in enumerate(phrases):
    keys.add(p['key'])
    dst = os.path.join(out_dir, p['key'] + '.mp3')
    if os.path.exists(dst):
        continue
    with tempfile.NamedTemporaryFile(suffix='.wav', delete=False) as tmp:
        wav_path = tmp.name
    with wave.open(wav_path, 'wb') as w:
        voice.synthesize_wav(p['text'], w, syn_config=cfg)
    subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', wav_path,
                    '-af', 'silenceremove=start_periods=1:start_threshold=-50dB,areverse,silenceremove=start_periods=1:start_threshold=-50dB,areverse,loudnorm=I=-16:TP=-1.5',
                    '-ac', '1', '-ar', '22050', '-b:a', '32k', dst], check=True)
    os.remove(wav_path)
    made += 1
    if made % 100 == 0:
        print(f'{made} new / {i + 1} of {len(phrases)}', flush=True)

for f in os.listdir(out_dir):
    if f.endswith('.mp3') and f[:-4] not in keys:
        os.remove(os.path.join(out_dir, f))

with open(os.path.join(out_dir, 'index.js'), 'w', encoding='utf-8') as fh:
    fh.write('/* generated by tools/make-audio.py */\nwindow.QAUDIO = {' + ','.join(f'"{k}":1' for k in sorted(keys)) + '};\n')
print(f'done: {made} new, {len(keys)} total')
